// Reed-Solomon codes over GF(64) with errors and erasures, the P25 codes among them,
// and the BCH(63,16,23) code of the P25 NID decoded as a binary subcode of one.
// Phil Karn's libfec (github.com/ka9q/libfec) has a general Reed-Solomon decoder,
// decode_rs_char(), that could do the Reed-Solomon part here (symbol size 6, field polynomial
// 0x43, first root alpha^1, with this file's rules for accepting a correction kept around it).
// It is not used, for build convenience only: it would be one more library to install, and
// the libfec-dev Debian packages is another revision whose decode_rs_char() numbers positions
// differently in a shortened code. The two decoders gave the same results when compared
// Copyright 2026, Matthew Kaufman, KA6SQG
#include <assert.h>
#include <pthread.h>
#include <stdbool.h>
#include <stdint.h>
#include <string.h>

#include "rs63.h"

// Theory of operation
//
// The field. GF(64) is the polynomials over GF(2) modulo x^6 + x + 1, which is primitive, so
// alpha = x has order 63 and every nonzero element is a power of it. Elements are kept in two
// forms, polynomial (6 bits, added by XOR) and index (the log to base alpha, multiplied by
// adding), with tables between them.
//
// The codes. A Reed-Solomon code with 'parity' check symbols here is the set of words c(x) of
// degree below 63 with c(alpha^i) = 0 for i = 1 .. parity; its minimum distance is parity + 1.
// The P25 codes are such (63,k) codes shortened: the top positions are held at zero and not
// sent. The syndromes S_i = r(alpha^i) of a received word are zero exactly for a codeword, and
// otherwise depend only on the error: S_i = sum of Y_k X_k^i over the errors, X_k = alpha^(their
// position), Y_k their values. Decoding finds the X_k and Y_k from the S_i.
//
// Errors only (rs_errors()). Berlekamp's iteration builds the error locator, the polynomial
// whose roots are the 1 / X_k, one syndrome at a time, keeping the shortest one consistent with
// the syndromes so far. A Chien search tries every alpha^i as a root, and Forney's formula gives
// each error's value from the locator and an error evaluator built from the syndromes. Up to
// parity / 2 errors are corrected.
//
// Errors and erasures (rs_erasures()). Positions known to be unreliable enter through their own
// locator Gamma(x) = prod (1 - X_j x). Multiplying the syndrome polynomial by it gives modified
// (Forney) syndromes in which the erasures no longer appear; Berlekamp-Massey on those finds the
// error locator Lambda(x), allowed degree (parity - erasures) / 2. Chien search and Forney then
// work on the errata locator Lambda(x) Gamma(x) and the evaluator S(x) Lambda(x) Gamma(x) mod
// x^parity. e errors and f erasures are corrected when 2e + f <= parity. With no erasures the
// errors-only path is used.
//
// Accepting a correction. Beyond its radius a decoder can still produce an answer, and these
// tests turn most such answers into failures:
//  - the error locator's degree must not exceed what the code corrects (errors only: a failure;
//    with erasures a longer one is replaced by 1, leaving the erasures alone to be corrected
//    and the last test to decide);
//  - the Chien search must find as many distinct roots as that degree: a locator that does not
//    split into distinct roots among the positions does not describe an error pattern;
//  - no correction may fall in a shortened code's zero padding, since the real code has no
//    symbol there;
//  - the corrected word (in binary mode, after truncation to bits) must have every syndrome zero.
// sym[] changes only when all pass.
//
// BCH(63,16,23). The P25 NID's binary code is the binary subcode of RS(63,41) with 22 parity:
// a binary word with zero syndromes S_1 .. S_22 is a multiple of every minimal polynomial of
// alpha^1 .. alpha^22, whose product is the BCH generator (47 roots, degree 47). So the
// Reed-Solomon decoder, erasures included, decodes it, and corrects 2e + f <= 22, the BCH code's
// own radius (distance 23). The Reed-Solomon decoder may reach a codeword with non-binary
// symbols; truncated to bits it fails the codeword test. The decode is then checked against the
// generator, which tests the same fact by other arithmetic, and 2e + f is counted again on the
// result. The soft variant erases, for each dibit below a confidence threshold (weakest first, at
// most 22), only the bit of the two that is in doubt, so each erasure is spent where an error is
// likely.

// GF(64) generated by x^6 + x + 1, primitive element alpha = x
enum {
  GF_M = 6,
  GF_N = 63,           // field period, and the length of every P25 RS code before shortening
  GF_POLY = 0x43,
  ALPHA_POW_SPAN = 4,  // alpha_pow[e] = alpha^(e mod 63) for e < 4 * 63: no division in the loops
  RS_MAXPAR = 28,      // most parity symbols of any P25 code (RS(63,35))
};

static int Alpha_to[GF_N+1];             // alpha^i, i = 0..62
static int Index_of[GF_N+1];             // log; Index_of[0] = -1
static int Alpha_pow[ALPHA_POW_SPAN * GF_N];

static pthread_once_t Once = PTHREAD_ONCE_INIT;

static void init_tables(void){
  int x = 1;
  for(int i = 0; i < GF_N; i++){
    Alpha_to[i] = x;
    Index_of[x] = i;
    x <<= 1;
    if(x & (1 << GF_M))
      x ^= GF_POLY;
  }
  Alpha_to[GF_N] = 0; // unused
  Index_of[0] = -1;
  for(int e = 0; e < ALPHA_POW_SPAN * GF_N; e++)
    Alpha_pow[e] = Alpha_to[e % GF_N];
}
static inline void init(void){
  pthread_once(&Once,init_tables);
}

// ---------------------------------------------------------------------------
// Reed-Solomon over GF(64)

static inline int gf_mul(int a,int b){
  if(a == 0 || b == 0)
    return 0;
  return Alpha_pow[Index_of[a] + Index_of[b]];
}
static inline int gf_inv(int a){
  if(a == 0)
    return 0;
  return Alpha_to[(GF_N - Index_of[a]) % GF_N];
}
// p[0] is the constant term
static int gf_poly_eval(int const *p,int len,int x){
  int r = 0;
  for(int i = len-1; i >= 0; i--)
    r = p[i] ^ gf_mul(r,x);
  return r;
}
// r = a * b; returns the length of r (a and b nonempty)
static int gf_poly_mul(int *r,int const *a,int alen,int const *b,int blen){
  int const rlen = alen + blen - 1;
  memset(r,0,rlen * sizeof *r);
  for(int i = 0; i < alen; i++)
    for(int j = 0; j < blen; j++)
      r[i+j] ^= gf_mul(a[i],b[j]);
  return rlen;
}

// True if all syndromes S1..S_parity of the word are zero
static bool is_codeword(int const *sym,int parity){
  for(int r = 1; r <= parity; r++){
    int acc = 0;
    int ij = 0; // (r * j) mod 63, stepped with j
    for(int j = 0; j < GF_N; j++){
      if(sym[j] != 0)
        acc ^= Alpha_pow[Index_of[sym[j]] + ij];
      ij += r;
      if(ij >= GF_N)
        ij -= GF_N;
    }
    if(acc != 0)
      return false;
  }
  return true;
}
bool rs63_is_codeword(uint8_t const sym[GF_N],int parity){
  assert(sym != NULL);
  assert(parity >= 1 && parity < GF_N);
  init();
  int s[GF_N];
  for(int i = 0; i < GF_N; i++)
    s[i] = sym[i] & GF_N;
  return is_codeword(s,parity);
}

// The decoded word as the caller sees it. In binary mode (the BCH code, decoded as the binary
// subcode of an RS code) each symbol is a bit, and a non-binary correction is truncated to 1;
// the codeword checks that follow then reject it
static void commit(int *out,int const *poly,bool binary){
  for(int i = 0; i < GF_N; i++)
    out[i] = binary ? (poly[i] != 0) : (poly[i] & GF_N);
}

// Errors-only decode: Berlekamp iteration for the error locator, Chien search for its roots,
// Forney for the error values. sym[] is updated only on success
// The iteration is the tabular form: row u of elp[] is the locator after u steps, d[u] its
// discrepancy (how far it misses the next syndrome), l[u] its degree. A nonzero discrepancy is
// cancelled by adding a scaled, shifted copy of the earlier row q with nonzero discrepancy and
// the largest q - l[q]. Most values are carried in index form, -1 standing for zero. A root
// alpha^i of the locator marks an error at position 63 - i. The evaluator here has
// z_i = sum over j = 0 .. i of S_j elp_(i-j), with S_0 = 1 and z_0 = 1, for i = 1 .. degree,
// and the value of the error at X_k is z(1/X_k) / prod over the other errors (1 - X_j / X_k)
static bool rs_errors(int *sym,int parity,int length,bool binary){
  int const tt = parity / 2;
  int elp[RS_MAXPAR+2][RS_MAXPAR];  // error locator, one row per iteration
  int d[RS_MAXPAR+2];               // discrepancy, index form
  int l[RS_MAXPAR+2];               // locator degree
  int u_lu[RS_MAXPAR+2];            // step minus degree
  int s[RS_MAXPAR+1];               // syndromes, index form (s[0] = 0: alpha^0)
  int root[RS_MAXPAR/2+1],loc[RS_MAXPAR/2+1];
  int z[RS_MAXPAR/2+1];             // error evaluator
  int reg[RS_MAXPAR/2+1];           // Chien search registers
  int err[GF_N];
  int recd[GF_N];                   // received word, index form
  int poly[GF_N];                   // received word, polynomial form, corrected in place

  memset(elp,0,sizeof elp);
  memset(d,0,sizeof d);
  memset(l,0,sizeof l);
  memset(u_lu,0,sizeof u_lu);
  memset(s,0,sizeof s);
  memset(z,0,sizeof z);
  memset(reg,0,sizeof reg);
  memset(err,0,sizeof err);
  for(int i = 0; i < GF_N; i++){
    recd[i] = Index_of[sym[i]];
    poly[i] = sym[i];
  }
  // Syndromes
  bool syn_error = false;
  for(int i = 1; i <= parity; i++){
    int acc = 0;
    int ij = 0;
    for(int j = 0; j < GF_N; j++){
      if(recd[j] != -1)
        acc ^= Alpha_pow[recd[j] + ij];
      ij += i;
      if(ij >= GF_N)
        ij -= GF_N;
    }
    if(acc != 0)
      syn_error = true;
    s[i] = Index_of[acc];
  }
  if(!syn_error)
    return true; // already a codeword

  // Berlekamp iteration
  d[0] = 0;
  d[1] = s[1];
  elp[0][0] = 0;
  elp[1][0] = 1;
  for(int i = 1; i < parity; i++){
    elp[0][i] = -1;
    elp[1][i] = 0;
  }
  l[0] = 0;
  l[1] = 0;
  u_lu[0] = -1;
  u_lu[1] = 0;
  int u = 0;
  do {
    u++;
    if(d[u] == -1){
      // Zero discrepancy
      l[u+1] = l[u];
      for(int i = 0; i <= l[u]; i++){
        elp[u+1][i] = elp[u][i];
        elp[u][i] = Index_of[elp[u][i]];
      }
    } else {
      // Find the earlier step q with nonzero discrepancy and largest q - l[q]
      int q = u - 1;
      while(d[q] == -1 && q > 0)
        q--;
      if(q > 0){
        int j = q;
        do {
          j--;
          if(d[j] != -1 && u_lu[q] < u_lu[j])
            q = j;
        } while(j > 0);
      }
      l[u+1] = l[u] > l[q] + u - q ? l[u] : l[q] + u - q;
      for(int i = 0; i < parity; i++)
        elp[u+1][i] = 0;
      for(int i = 0; i <= l[q]; i++){
        if(elp[q][i] != -1)
          elp[u+1][i + u - q] = Alpha_pow[d[u] + GF_N - d[q] + elp[q][i]];
      }
      for(int i = 0; i <= l[u]; i++){
        elp[u+1][i] ^= elp[u][i];
        elp[u][i] = Index_of[elp[u][i]];
      }
    }
    u_lu[u+1] = u - l[u+1];
    // Next discrepancy
    if(u < parity){
      d[u+1] = s[u+1] != -1 ? Alpha_to[s[u+1]] : 0;
      for(int i = 1; i <= l[u+1]; i++){
        if(s[u+1-i] != -1 && elp[u+1][i] != 0)
          d[u+1] ^= Alpha_pow[s[u+1-i] + Index_of[elp[u+1][i]]];
      }
      d[u+1] = Index_of[d[u+1]];
    }
  } while(u < parity && l[u+1] <= tt);
  u++;
  if(l[u] > tt)
    return false; // more errors than the code corrects

  // Chien search for the roots of the locator
  for(int i = 0; i <= l[u]; i++)
    elp[u][i] = Index_of[elp[u][i]];
  for(int i = 1; i <= l[u]; i++)
    reg[i] = elp[u][i];
  int count = 0;
  for(int i = 1; i <= GF_N; i++){
    int q = 1;
    for(int j = 1; j <= l[u]; j++){
      if(reg[j] != -1){
        reg[j] += j;
        if(reg[j] >= GF_N)
          reg[j] -= GF_N;
        q ^= Alpha_to[reg[j]];
      }
    }
    if(q == 0){
      assert(count < RS_MAXPAR/2+1);
      root[count] = i;
      loc[count] = GF_N - i;
      count++;
    }
  }
  if(count != l[u])
    return false; // the locator does not split: too many errors

  // Error evaluator z(x)
  for(int i = 1; i <= l[u]; i++){
    if(s[i] != -1 && elp[u][i] != -1)
      z[i] = Alpha_to[s[i]] ^ Alpha_to[elp[u][i]];
    else if(s[i] != -1)
      z[i] = Alpha_to[s[i]];
    else if(elp[u][i] != -1)
      z[i] = Alpha_to[elp[u][i]];
    else
      z[i] = 0;
    for(int j = 1; j < i; j++){
      if(s[j] != -1 && elp[u][i-j] != -1)
        z[i] ^= Alpha_pow[elp[u][i-j] + s[j]];
    }
    z[i] = Index_of[z[i]];
  }
  // Error values (Forney)
  for(int i = 0; i < l[u]; i++){
    err[loc[i]] = 1; // z[0]
    for(int j = 1; j <= l[u]; j++){
      if(z[j] != -1)
        err[loc[i]] ^= Alpha_to[(z[j] + j * root[i]) % GF_N];
    }
    if(err[loc[i]] != 0){
      err[loc[i]] = Index_of[err[loc[i]]];
      int q = 0; // denominator
      for(int j = 0; j < l[u]; j++){
        if(j != i)
          q += Index_of[1 ^ Alpha_pow[loc[j] + root[i]]];
      }
      q = q % GF_N;
      err[loc[i]] = Alpha_to[(err[loc[i]] - q + GF_N) % GF_N];
      poly[loc[i]] ^= err[loc[i]];
    }
  }
  // A correction in the shortened code's zero padding is not a codeword of the real code
  for(int i = length; i < GF_N; i++){
    if(poly[i] != sym[i])
      return false;
  }
  int out[GF_N];
  commit(out,poly,binary);
  if(!is_codeword(out,parity))
    return false;
  memcpy(sym,out,sizeof out);
  return true;
}

// Berlekamp-Massey LFSR synthesis on S[1..n]; writes the connection polynomial (c[0] = 1)
// and returns its length. Exceeding maxdeg returns the identity (no correction)
enum { BM_MAX = 2 * RS_MAXPAR + 4 };
static int bm_lfsr(int *c,int const *S,int n,int maxdeg){
  int b[BM_MAX],t[BM_MAX];
  int clen = 1,blen = 1;
  c[0] = 1;
  b[0] = 1;
  int L = 0;
  int m = 1;
  int bd = 1; // previous discrepancy
  for(int r = 1; r <= n; r++){
    int delta = S[r];
    for(int i = 1; i < clen; i++){
      int const k = r - i;
      if(k >= 1 && k <= n && c[i] != 0 && S[k] != 0)
        delta ^= gf_mul(c[i],S[k]);
    }
    if(delta == 0){
      m++;
    } else {
      // t(x) = c(x) + (delta / bd) x^m b(x)
      int tlen = clen;
      memcpy(t,c,clen * sizeof *t);
      int const db = gf_mul(delta,gf_inv(bd));
      if(blen + m > tlen){
        assert(blen + m <= BM_MAX);
        for(int i = tlen; i < blen + m; i++)
          t[i] = 0;
        tlen = blen + m;
      }
      for(int i = 0; i < blen; i++)
        t[i+m] ^= gf_mul(db,b[i]);
      if(2 * L <= r - 1){
        memcpy(b,c,clen * sizeof *b);
        blen = clen;
        L = r - L;
        bd = delta;
        m = 1;
      } else {
        m++;
      }
      memcpy(c,t,tlen * sizeof *c);
      clen = tlen;
    }
    if(L > maxdeg){
      c[0] = 1;
      return 1;
    }
  }
  return clen;
}

// Errors-and-erasures decode: erasure locator Gamma(x), Forney (modified) syndromes,
// Berlekamp-Massey for the error locator Lambda(x), Chien search on Lambda(x)Gamma(x),
// Forney for the values. sym[] is updated only on success
// The roots are found by evaluating the errata locator at alpha^-p for every position p. With
// the first root alpha^1, Forney's formula needs no X^(1-b) factor: e = omega(1/X) / sigma'(1/X)
static bool rs_erasures(int *sym,int parity,int length,bool binary,int const *erasures,int t){
  if(t == 0)
    return rs_errors(sym,parity,length,binary);
  if(t > parity)
    return false;

  int poly[GF_N];
  memcpy(poly,sym,sizeof poly);
  // Syndromes S[1..parity], polynomial form
  int S[RS_MAXPAR+1];
  memset(S,0,sizeof S);
  bool has_error = false;
  for(int i = 1; i <= parity; i++){
    int acc = 0;
    int ij = 0;
    for(int j = 0; j < GF_N; j++){
      if(poly[j] != 0)
        acc ^= Alpha_pow[Index_of[poly[j]] + ij];
      ij += i;
      if(ij >= GF_N)
        ij -= GF_N;
    }
    S[i] = acc;
    if(acc != 0)
      has_error = true;
  }
  if(!has_error)
    return true;

  // Erasure locator Gamma(x) = prod (1 - alpha^pos x)
  int gamma[RS_MAXPAR+1];
  memset(gamma,0,sizeof gamma);
  gamma[0] = 1;
  for(int j = 0; j < t; j++){
    int const ea = Alpha_to[erasures[j] % GF_N];
    for(int i = j + 1; i > 0; i--){
      if(gamma[i-1] != 0)
        gamma[i] ^= gf_mul(ea,gamma[i-1]);
    }
  }
  // Modified syndromes T[t+1..parity] of Gamma(x)S(x), renumbered 1..parity-t
  int const modcount = parity - t;
  int tmod[RS_MAXPAR+1];
  memset(tmod,0,sizeof tmod);
  for(int i = 1; i <= modcount; i++){
    int const ti = t + i;
    int sum = 0;
    for(int j = 0; j <= t; j++){
      int const k = ti - j;
      if(k >= 1 && k <= parity && gamma[j] != 0 && S[k] != 0)
        sum ^= gf_mul(gamma[j],S[k]);
    }
    tmod[i] = sum;
  }
  int lambda[BM_MAX];
  int const lambda_len = bm_lfsr(lambda,tmod,modcount,modcount/2);

  // Errata locator sigma(x) = Lambda(x)Gamma(x); Chien search
  int sigma[BM_MAX + RS_MAXPAR + 1];
  int const sigma_len = gf_poly_mul(sigma,lambda,lambda_len,gamma,t+1);
  int const sig_deg = sigma_len - 1;
  int pos[GF_N];
  int npos = 0;
  for(int p = 0; p < GF_N; p++){
    if(gf_poly_eval(sigma,sigma_len,Alpha_to[(GF_N - p % GF_N) % GF_N]) == 0)
      pos[npos++] = p;
  }
  if(npos != sig_deg)
    return false;
  for(int i = 0; i < npos; i++){
    if(pos[i] >= length)
      return false; // a "correction" in the zero padding: not a codeword of the real code
  }
  // Errata evaluator omega(x) = S(x)sigma(x) mod x^parity, S(x) = S1 + S2 x + ...
  int omega[RS_MAXPAR + BM_MAX + RS_MAXPAR + 1];
  int omega_len = gf_poly_mul(omega,S+1,parity,sigma,sigma_len);
  if(omega_len > parity)
    omega_len = parity;
  // Formal derivative: only odd powers survive in characteristic 2
  int sigma_prime[BM_MAX + RS_MAXPAR + 1];
  memset(sigma_prime,0,sigma_len * sizeof *sigma_prime);
  for(int i = 1; i < sigma_len; i++){
    if(i & 1)
      sigma_prime[i-1] = sigma[i];
  }
  // Forney: e = omega(X^-1) / sigma'(X^-1), X = alpha^pos
  for(int i = 0; i < npos; i++){
    int const xinv = Alpha_to[(GF_N - pos[i] % GF_N) % GF_N];
    int const num = gf_poly_eval(omega,omega_len,xinv);
    int const den = gf_poly_eval(sigma_prime,sigma_len,xinv);
    if(den == 0)
      continue;
    poly[pos[i]] ^= gf_mul(num,gf_inv(den));
  }
  int out[GF_N];
  commit(out,poly,binary);
  if(!is_codeword(out,parity))
    return false; // the erasure decoder can "succeed" on a non-codeword
  memcpy(sym,out,sizeof out);
  return true;
}

int rs63_decode(uint8_t sym[GF_N],int parity,int length,int const *erasures,int nerasures){
  assert(sym != NULL);
  assert(parity >= 1 && parity <= RS_MAXPAR);
  assert(length > parity && length <= GF_N);
  assert(nerasures >= 0 && (nerasures == 0 || erasures != NULL));
  init();
  int w[GF_N];
  for(int i = 0; i < GF_N; i++)
    w[i] = sym[i] & GF_N;
  for(int i = 0; i < nerasures; i++)
    assert(erasures[i] >= 0 && erasures[i] < GF_N);

  if(!rs_erasures(w,parity,length,false,erasures,nerasures))
    return -1;
  int changed = 0;
  for(int i = 0; i < GF_N; i++){
    if(w[i] != (sym[i] & GF_N))
      changed++;
    sym[i] = w[i];
  }
  return changed;
}

// ---------------------------------------------------------------------------
// BCH(63,16,23), the P25 NID

enum { BCH_N = 63, BCH_REDUNDANCY = 22 }; // 22 syndromes (designed distance 23)
// The product of the minimal polynomials of alpha^1 .. alpha^22 in this file's field
static uint64_t const Bch_generator = 06331141367235453ULL; // bit i = coefficient of x^i, degree 47

static uint64_t bch_remainder(uint64_t w){
  for(int b = 62; b >= 47; b--){
    if((w >> b) & 1)
      w ^= Bch_generator << (b - 47);
  }
  return w;
}

int bch_63_16_decode(uint8_t bits[BCH_N],int const *erasures,int nerasures){
  assert(bits != NULL);
  assert(nerasures >= 0 && (nerasures == 0 || erasures != NULL));
  init();
  // Bit k is the coefficient of x^(62-k), i.e. RS position 62 - k
  int w[GF_N];
  uint64_t received = 0;
  for(int k = 0; k < BCH_N; k++){
    w[62-k] = bits[k] ? 1 : 0;
    if(bits[k])
      received |= 1ULL << (62 - k);
  }
  int rev[GF_N + 1];
  int t = 0;
  uint64_t erased = 0;
  for(int i = 0; i < nerasures; i++){
    if(erasures[i] >= 0 && erasures[i] < BCH_N){
      if(t >= BCH_REDUNDANCY)
        return -1; // too many
      rev[t++] = 62 - erasures[i];
      erased |= 1ULL << (62 - erasures[i]);
    }
  }
  if(!rs_erasures(w,BCH_REDUNDANCY,GF_N,true,rev,t))
    return -1;

  // Only a BCH codeword is a decode
  uint64_t corrected = 0;
  for(int i = 0; i < GF_N; i++){
    if(w[i])
      corrected |= 1ULL << i;
  }
  if(bch_remainder(corrected) != 0)
    return -1;
  int const errors = __builtin_popcountll((received ^ corrected) & ~erased);
  if(2 * errors + t > BCH_REDUNDANCY)
    return -1;
  for(int k = 0; k < BCH_N; k++)
    bits[k] = (corrected >> (62 - k)) & 1;
  return __builtin_popcountll(received ^ corrected);
}

int bch_63_16_decode_soft(uint8_t bits[BCH_N],float const confidence[32],bool const lsb_ambiguous[32],float threshold){
  assert(bits != NULL && confidence != NULL && lsb_ambiguous != NULL);
  int r = bch_63_16_decode(bits,NULL,0);
  if(r >= 0)
    return r;

  // Dibits, weakest first (stable: equal confidences in dibit order)
  int order[32];
  for(int j = 0; j < 32; j++){
    int i = j;
    while(i > 0 && confidence[order[i-1]] > confidence[j]){
      order[i] = order[i-1];
      i--;
    }
    order[i] = j;
  }
  int erasures[BCH_REDUNDANCY];
  int n = 0;
  for(int k = 0; k < 32; k++){
    int const j = order[k];
    if(confidence[j] >= threshold || n >= BCH_REDUNDANCY)
      break;
    int const bit = 2 * j + (lsb_ambiguous[j] ? 1 : 0);
    if(bit < BCH_N)
      erasures[n++] = bit; // bit 63 is the NID parity bit, not part of the BCH word
  }
  if(n == 0)
    return -1;
  return bch_63_16_decode(bits,erasures,n);
}
